def _new_calc(p: int) -> int:
    """新契約（平成24年1月1日以後）の控除額。"""
    if p <= 20000:
        return p
    if p <= 40000:
        return p // 2 + 10000
    if p <= 80000:
        return p // 4 + 20000
    return 40000


def _old_calc(p: int) -> int:
    """旧契約（平成23年12月31日以前）の控除額。"""
    if p <= 25000:
        return p
    if p <= 50000:
        return p // 2 + 12500
    if p <= 100000:
        return p // 4 + 25000
    return 50000


