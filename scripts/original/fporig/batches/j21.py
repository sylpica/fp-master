def _pmt(principal: float, annual_rate: float, months: int) -> float:
    """元利均等返済の毎月返済額（未丸め）。"""
    r = annual_rate / 12
    return principal * r * (1 + r) ** months / ((1 + r) ** months - 1)


def _r0(x: float) -> int:
    """円未満を四捨五入して整数にする。"""
    return int(math.floor(x + 0.5))


