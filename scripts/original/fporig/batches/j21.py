def _simulate(balance: float, monthly_rate: float, payment: int) -> tuple[int, float]:
    """毎月返済額 payment で返済を続けた場合の（返済回数，利息総額）。
    各月の利息は返済前の残高×月利。最終回は残高とその月の利息の合計を返済する。"""
    months = 0
    interest = 0.0
    b = float(balance)
    while b > 0:
        i = b * monthly_rate
        months += 1
        interest += i
        if b + i <= payment:
            b = 0.0
        else:
            b -= (payment - i)
    return months, interest


