def _yen(v: int) -> str:
    oku, man = v // 100_000_000, (v % 100_000_000) // 10_000
    s = f'{oku}億' if oku else ''
    if man:
        s += f'{man:,}万円'
    elif s:
        s += '円'
    return s if s else '0円'


