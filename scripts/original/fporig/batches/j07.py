def _quick(amount: int) -> int:
    """相続税の速算表（資料）による税額。"""
    table = [(10000000, Fraction(10, 100), 0), (30000000, Fraction(15, 100), 500000),
             (50000000, Fraction(20, 100), 2000000), (100000000, Fraction(30, 100), 7000000),
             (200000000, Fraction(40, 100), 17000000), (300000000, Fraction(45, 100), 27000000),
             (600000000, Fraction(50, 100), 42000000), (None, Fraction(55, 100), 72000000)]
    for cap, rate, ded in table:
        if cap is None or amount <= cap:
            return int(amount * rate) - ded
    raise AssertionError


