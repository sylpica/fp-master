# ── Q7（回収期間法）の数値はすべてコードで計算する ──
_P_INV = 3600          # 初期投資額（万円）
_P_CF = 900            # 毎年の純キャッシュ・フロー（万円）
_PBP_YEARS = _P_INV / _P_CF            # 正答：単純回収期間 4年
_P_INVERSE = _P_CF / _P_INV            # 式を取り違えた誤り 0.25年


def _discounted_payback_year(inv: float, cf: float, r: float) -> int:
    """割引回収期間法（DPP法）で回収に要する年数（割引率5％の誤り肢用）"""
    cum, year = 0.0, 0
    while cum < inv and year < 50:
        year += 1
        cum += cf / (1 + r) ** year
    return year


