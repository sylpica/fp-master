def apply_examples(terms: list[dict]) -> int:
    """example がない用語に EXAMPLES の具体例を補う。補った件数を返す。"""
    by_id = {t['id']: t for t in terms}
    unknown = sorted(set(EXAMPLES) - set(by_id))
    if unknown:
        raise SystemExit(f'glossary_examples_src: 存在しない用語ID {unknown}')
    dup = sorted(k for k in EXAMPLES if by_id[k].get('example'))
    if dup:
        raise SystemExit(f'glossary_examples_src: すでに example がある用語 {dup}（元の原稿を直すこと）')
    for k, v in EXAMPLES.items():
        by_id[k]['example'] = v
