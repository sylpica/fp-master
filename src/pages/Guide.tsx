/** 出現頻度の低いパターン（例：特定役員退職手当等）まで拾える試行回数。開いた種別だけ計算する */
const SAMPLE_SEEDS = 200;

/** 生成器を実際に動かし、難易度別の出題パターン・与えられる値・端数処理・単位を集める */
function describeGenerator(g: CalcGenerator) {
  const patterns: Record<Difficulty, Set<string>> = { 1: new Set(), 2: new Set(), 3: new Set() };
  const labels = new Set<string>();
  const rounding = new Set<string>();
  const units = new Set<string>();
  for (const d of [1, 2, 3] as Difficulty[]) {
    for (let seed = 1; seed <= SAMPLE_SEEDS; seed++) {
      const p = g.generate(seed, d);
      patterns[d].add(p.pattern);
      for (const x of p.given) labels.add(x.label.split(/[ （(]/)[0]!);
      if (p.roundingNote) rounding.add(p.roundingNote);
      if (p.unit) units.add(p.unit);
    }
  }
  return {
    patterns: ([1, 2, 3] as Difficulty[]).map((d) => ({ d, list: [...patterns[d]] })),
    labels: [...labels],
    rounding: [...rounding],
    units: [...units],
  };
}

const DIFFICULTY_NAMES: Record<Difficulty, string> = { 1: '基本', 2: '標準', 3: '応用' };

function GeneratorDetail({ g }: { g: CalcGenerator }) {
  const info = useMemo(() => describeGenerator(g), [g]);
  return (
    <div className="mt-1 space-y-0.5 text-slate-600 dark:text-slate-400">
      {info.patterns.map((p) => (
        <div key={p.d}>
          {DIFFICULTY_NAMES[p.d]}：{p.list.join('・')}
        </div>
      ))}
      <div>与えられる値：{info.labels.join('・')}</div>
      <div>
        答えの単位：{info.units.join('・')}
        {info.rounding.length > 0 && `／端数処理：${info.rounding.join('・')}`}
      </div>
    </div>
  );
}

function GeneratorItem({ g }: { g: CalcGenerator }) {
  const [open, setOpen] = useState(false);
  return (
    <li className="border-b border-slate-100 pb-3 last:border-0 dark:border-slate-800">
      <div className="font-medium">
        {g.title}（{FIELDS[g.field].name}）
      </div>
      <div className="text-slate-600 dark:text-slate-400">基準：<TermText text={g.basis} /></div>
      <div className="break-words text-slate-600 dark:text-slate-400">
        出典：
        {g.sources.map((s) => (
          <a key={s.url} className="mr-2 underline" href={s.url} target="_blank" rel="noreferrer">
            {s.title}
          </a>
        ))}
      </div>
      <details onToggle={(e) => setOpen((e.currentTarget as HTMLDetailsElement).open)}>
        <summary className="min-h-10 cursor-pointer pt-2 text-brand-700 dark:text-brand-200">難易度別の出題パターンと与えられる値</summary>
        {open && <GeneratorDetail g={g} />}
      </details>
    </li>
  );
}

